window.renderRuleArticle = function (key) {
  const r = window.RULES[key];
  const e = window.UI.esc;
  return r.sections.map(s => `<section class="rule-sec"><h3 class="rule-sec__h">${e(s.h)}</h3>
    ${(s.p || []).map(t => `<p class="rule-sec__p">${e(t)}</p>`).join('')}
    ${(s.items || []).map(([k, v]) => `<p class="rule-sec__p"><b class="rule-sec__k">${e(k)}</b>${e(v)}</p>`).join('')}</section>`).join('');
};
